package tokenize

// 中英常见虚词。bigram 保底仍覆盖实体词，停用词只降低噪声。
var defaultStop = map[string]struct{}{
	"the": {}, "a": {}, "an": {}, "and": {}, "or": {}, "of": {}, "to": {}, "in": {},
	"on": {}, "for": {}, "is": {}, "are": {}, "was": {}, "were": {}, "be": {},
	"this": {}, "that": {}, "with": {}, "as": {}, "by": {}, "at": {}, "from": {},
	"it": {}, "its": {}, "we": {}, "you": {}, "they": {}, "i": {},
	"的": {}, "了": {}, "和": {}, "与": {}, "及": {}, "或": {}, "在": {}, "是": {},
	"我": {}, "你": {}, "他": {}, "她": {}, "它": {}, "们": {}, "这": {}, "那": {},
	"一个": {}, "一种": {}, "以及": {}, "如果": {}, "因为": {}, "所以": {},
	"我们": {}, "可以": {}, "进行": {}, "通过": {}, "对于": {}, "然后": {},
}

func isStop(term string) bool {
	_, ok := defaultStop[term]
	return ok
}
